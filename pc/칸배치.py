"""**칸을 사람이 옮긴다** — 어느 칸을 어디에 둘지 (오너 2026-09-28).

오른쪽 줄에는 최근·살핌·폴더·코드·앞머리·제안·활동·모델… 이 **박아 놓은 차례**로
쌓여 있었다. 아래에는 범례·말·새 판 띠·채팅이 같은 꼴로 박혀 있었다. 쓰는 사람마다
매일 보는 것이 다른데 차례를 코드가 정하고 있었다.

바꾼 것: **칸마다 이름을 주고, 어디에 둘지를 설정에 남긴다.**

자리는 셋이다:

| `우` | 오른쪽 줄 |
| `아래` | 그래프 밑 |
| `숨김` | 안 그린다 |

★★ **없는 이름은 버리고, 새 이름은 뒤에 붙인다.** 판이 올라 칸이 하나 늘었는데
   설정에 그 이름이 없으면, 고지식하게 설정만 따르면 **새 칸이 영영 안 보인다** —
   사람은 그것이 생긴 줄도 모른다. 반대로 없어진 칸 이름이 설정에 남아 있으면
   그리다 터진다. 그래서 **읽을 때 기본과 맞춘다.**
★ 이 파일은 **꼴만 안다.** 무엇을 그릴지는 `ui.py` 가 안다 — 여기에 위젯이 없다.
"""
from __future__ import annotations

import paths

자리들 = ("우", "아래", "숨김")

# 칸 이름 → (보일 이름, 기본 자리). **차례가 기본 차례다.**
# ★ 이름은 **안 바꾼다** — 설정에 남은 이름이 이것과 맞아야 자리가 지켜진다.
기본칸 = (
    ("찾은것", "찾은 것", "우"),
    ("최근", "최근", "우"),
    ("살핌", "살핌", "우"),
    ("폴더", "폴더", "우"),
    ("코드", "코드", "우"),
    ("앞머리", "앞머리", "우"),
    ("아직없는것", "아직 없는 것", "우"),
    ("언제", "언제", "우"),
    ("제안", "제안", "우"),
    ("활동", "활동", "우"),
    ("모델", "모델", "우"),
    ("상태", "상태·기록", "우"),
    ("범례", "색 범례", "아래"),
    ("말", "VC 가 하는 말", "아래"),
    ("새판", "새 판 알림", "아래"),
    ("채팅", "채팅", "아래"),
)

이름들 = tuple(ㄱ for ㄱ, _, _ in 기본칸)
보일이름 = {ㄱ: ㄴ for ㄱ, ㄴ, _ in 기본칸}
기본자리 = {ㄱ: ㄷ for ㄱ, _, ㄷ in 기본칸}


def 기본() -> list[tuple[str, str]]:
    """손 안 댄 배치. `[(이름, 자리), …]` — 차례가 그리는 차례다."""
    return [(ㄱ, ㄷ) for ㄱ, _, ㄷ in 기본칸]


def 맞추기(적힌것) -> list[tuple[str, str]]:
    """설정에 적힌 것을 **지금 있는 칸에 맞춘다.**

    ★★ 없어진 이름은 버리고, **새로 생긴 이름은 기본 자리로 뒤에 붙인다.**
       안 붙이면 판이 오를 때마다 새 칸이 아무도 모르게 사라진다.
    """
    난것: list[tuple[str, str]] = []
    본것 = set()
    # ★ 설정 파일은 사람이 손으로도 고친다. **꼴이 아니면 그냥 기본으로 간다** —
    #   여기서 터지면 설정 한 줄 때문에 창이 아예 안 뜬다.
    if not isinstance(적힌것, (list, tuple)):
        적힌것 = ()
    for 것 in 적힌것:
        이름 = 자리 = ""
        if isinstance(것, (list, tuple)) and len(것) >= 2:
            이름, 자리 = str(것[0]), str(것[1])
        elif isinstance(것, dict):
            이름, 자리 = str(것.get("이름") or ""), str(것.get("자리") or "")
        if 이름 not in 보일이름 or 이름 in 본것:
            continue
        본것.add(이름)
        난것.append((이름, 자리 if 자리 in 자리들 else 기본자리[이름]))
    for 이름, _, 자리 in 기본칸:
        if 이름 not in 본것:
            난것.append((이름, 자리))
    return 난것


def 읽기() -> list[tuple[str, str]]:
    """설정에 남은 배치. 없으면 기본."""
    try:
        적힌 = paths.load_config().get("칸배치")
    except Exception:
        적힌 = None
    return 맞추기(적힌) if 적힌 else 기본()


def 쓰기(배치) -> None:
    """배치를 설정에 남긴다. 다음에 켤 때 그대로 뜬다."""
    cfg = paths.load_config()
    paths.save_config({**cfg, "칸배치": [[ㄱ, ㄴ] for ㄱ, ㄴ in 맞추기(배치)]})


def 자리별(배치) -> dict[str, list[str]]:
    """`{자리: [이름, …]}`. 차례는 배치 차례 그대로."""
    난것: dict[str, list[str]] = {ㄱ: [] for ㄱ in 자리들}
    for 이름, 자리 in 배치:
        난것.setdefault(자리, []).append(이름)
    return 난것


def _self_check() -> None:
    import tempfile
    from pathlib import Path

    assert set(이름들) == set(보일이름), "이름 표가 어긋났다"
    assert len(이름들) == len(기본칸), "이름이 겹친다"
    for _, 자리 in 기본():
        assert 자리 in 자리들, 자리

    # ★★ **새로 생긴 칸은 뒤에 붙는다.** 안 붙이면 판이 올라 칸이 늘어도
    #   설정을 한 번 저장해 둔 사람에게는 **영영 안 보인다.**
    옛것 = [["최근", "아래"], ["코드", "숨김"]]
    맞춘 = 맞추기(옛것)
    assert 맞춘[0] == ("최근", "아래") and 맞춘[1] == ("코드", "숨김"), 맞춘[:2]
    assert set(ㄱ for ㄱ, _ in 맞춘) == set(이름들), "새 칸이 빠졌다"
    assert dict(맞춘)["채팅"] == 기본자리["채팅"], "새 칸이 기본 자리로 안 붙었다"

    # ★ 없어진 이름·이상한 자리는 버린다 — 그리다 터지면 창이 안 뜬다
    맞춘2 = 맞추기([["없는칸", "우"], ["최근", "달나라"], ["최근", "숨김"]])
    assert "없는칸" not in dict(맞춘2), 맞춘2
    assert dict(맞춘2)["최근"] == 기본자리["최근"], "이상한 자리를 그대로 썼다"
    assert [ㄱ for ㄱ, _ in 맞춘2].count("최근") == 1, "같은 칸이 두 번 들었다"

    # ★ 꼴이 아예 아닌 것도 삼킨다(설정 파일은 사람이 손으로도 고친다).
    #   여기서 터지면 **창이 아예 안 뜬다** — 설정 한 줄 때문에 프로그램이 죽는다.
    for 엉뚱 in (["최근", 3, None, {}], "엉뚱한글", 7, {"최근": "우"}):
        assert set(ㄱ for ㄱ, _ in 맞추기(엉뚱)) == set(이름들), 엉뚱

    갈린것 = 자리별([("가", "우"), ("나", "아래"), ("다", "우")])
    assert 갈린것["우"] == ["가", "다"] and 갈린것["아래"] == ["나"], 갈린것

    # --- 남고 다시 읽힌다 ---
    옛자리 = paths.state_dir
    곳 = Path(tempfile.mkdtemp())
    paths.state_dir = lambda: 곳
    try:
        paths.save_config({})
        쓰기([("채팅", "우"), ("최근", "숨김")])
        읽은 = 읽기()
        assert 읽은[0] == ("채팅", "우") and 읽은[1] == ("최근", "숨김"), 읽은[:2]
        assert set(ㄱ for ㄱ, _ in 읽은) == set(이름들), "다시 읽으니 칸이 빠졌다"
    finally:
        paths.state_dir = 옛자리
    print("칸배치 self-check 통과")


if __name__ == "__main__":
    import sys

    if "--check" in sys.argv:
        _self_check()
