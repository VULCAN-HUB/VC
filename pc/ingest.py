"""흡수 — 이미 있는 파일을 항목으로 들인다. **화면도 모델도 안 쓴다.**

여기가 따로 있는 이유는 `orders.py`와 같다. 지금은 디스크의 글을 들이지만
나중에는 글라스가 들은 것을 들인다. **들이는 일**과 **어디서 오는지**가 한 덩어리면
그때 두 벌이 된다.

## 원본은 안 옮긴다

파일이 그대로 원본층이다. 항목은 그 자리와 줄 번호만 지고 다닌다.
옮기면 같은 글이 두 벌이 되고, 밖에서 고쳤을 때 어느 쪽이 참인지 알 길이 없어진다.
디스크에 이미 있는 것을 또 쌓는 것은 20년짜리 물건에서 특히 나쁘다.

## 문지기는 두 겹이다

여기 있는 것은 **싼 쪽**뿐이다 — 길이·기호 비율·같은 글 같은, 읽지 않고도 아는 것.
「이게 나중에 쓸모 있나」는 여기서 안 판단한다. 그건 모델이 할 일이고 조각마다
1초씩 든다. **싼 문지기로 명백한 것을 먼저 걷어내야** 비싼 문지기가 볼 것이 준다.
"""
from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass, field
from pathlib import Path

# 딸려 온 남의 것. 훑을 값이 없고, 안 걸러내면 이것들이 항목의 대부분이 된다.
남의것 = re.compile(r"(^|[\\/])(node_modules|venv|\.venv|site-packages|\.git|"
                    r"dist|build|__pycache__|\.mypy_cache|\.pytest_cache)([\\/]|$)")

# 사람이 안 쓴 글. 이름만 봐도 안다.
기계글 = re.compile(r"^(LICENSE|CHANGELOG|robots|CODE_OF_CONDUCT|"
                    r"package-lock|poetry\.lock|requirements)", re.I)

# 조각 하나가 이보다 길면 더 쪼갠다. 한 항목이 너무 길면 뜻 벡터가 흐려져서
# 「무엇에 대한 글인지」가 사라진다 — 찾기 점수에서 실제로 그렇게 나왔다.
긴조각 = 1400
# 이보다 짧으면 안 들인다. 표제만 남은 껍데기가 이 밑에 몰려 있다.
짧은조각 = 40


@dataclass
class 조각:
    제목: str
    몸: str
    출처: str          # 뿌리에서부터의 상대 경로
    줄: int            # 원본에서 이 조각이 시작한 줄 (1부터)

    @property
    def 지문(self) -> str:
        """같은 글을 두 번 안 들이려고 쓴다. **공백만 다른 것도 같은 글로 본다** —
        같은 문서가 폴더 두 곳에 복사돼 있는 일이 흔하고, 그때 줄바꿈만 달라진다."""
        굳힌 = " ".join(self.몸.split())
        return hashlib.blake2b(굳힌.encode("utf-8"), digest_size=16).hexdigest()


def 조각내기(raw: str, 출처: str = "") -> list[조각]:
    """표제를 따라 나눈다. 표제가 없거나 한 도막이 길면 빈 줄로 더 나눈다.

    표제 단위로 나누는 이유: 사람이 글을 나눠 놓은 자리가 곧 뜻이 갈리는 자리다.
    우리가 글자 수로 자르면 문장 한복판이 잘려서 조각이 무슨 말인지 모르게 된다.
    """
    줄들 = raw.splitlines()
    # ★ **앞머리(front matter)는 글이 아니다.** `---` 로 감싼 YAML 을 그냥 두면
    # 「title: 무엇」이 표제로 잡히고 몸은 `---` 한 줄만 남는다 — 실사용에서
    # 그런 항목이 둘 들어왔다. 앞머리를 건너뛰되 **`title:` 값은 그 문서의 이름으로
    # 쓴다.** 사람이 거기 적어 둔 이름이라 파일 이름보다 낫다.
    앞머리제목, 건너뛴줄 = "", 0
    if 줄들 and 줄들[0].strip() == "---":
        for i, 줄 in enumerate(줄들[1:], 2):
            if 줄.strip() == "---":
                건너뛴줄 = i
                break
            if m := re.match(r"^(?:title|제목)\s*:\s*(.+)$", 줄.strip()):
                앞머리제목 = m.group(1).strip().strip("\"'")
        else:
            건너뛴줄 = 0        # 안 닫혔으면 앞머리가 아니다. 손대지 않는다
    줄들 = 줄들[건너뛴줄:]

    도막: list[tuple[str, int, list[str]]] = []
    이름, 첫줄, 담을 = 앞머리제목, 건너뛴줄 + 1, []
    코드안 = False
    # `자리` 는 잘라 낸 줄들 안에서의 자리, `줄번호` 는 **원본 파일에서의 줄**이다.
    # 앞머리를 건너뛰면 둘이 어긋나므로 갈라 둔다 — 항목이 지고 다니는 것은 줄번호다.
    for 자리, 줄 in enumerate(줄들):
        줄번호 = 건너뛴줄 + 자리 + 1
        # **코드 울타리 안의 우물 정은 표제가 아니다.** 파이썬 주석이 통째로 표제로
        # 읽히면 한 파일이 주석 수만큼 조각난다.
        if 줄.lstrip().startswith("```"):
            코드안 = not 코드안
        다음 = 줄들[자리 + 1] if 자리 + 1 < len(줄들) else ""
        표제 = "" if 코드안 else _표제(줄, 다음)
        if 표제:
            if 담을 or 이름:
                도막.append((이름, 첫줄, 담을))
            이름, 첫줄, 담을 = 표제, 줄번호, []
        else:
            담을.append(줄)
    if 담을 or 이름:
        도막.append((이름, 첫줄, 담을))

    나온: list[조각] = []
    밑동 = Path(출처).stem if 출처 else ""
    쓴제목: dict[str, int] = {}
    for 이름, 첫줄, 담을 in 도막:
        몸 = "\n".join(담을).strip()
        if not 몸:
            continue
        for 몇째, (곁, 더한줄) in enumerate(_쪼개기(몸, 첫줄)):
            # ★ **큰 도막이 여러 조각으로 쪼개질 때 첫 조각만 그 표제를 쓴다.**
            # log.md 처럼 표제 하나 밑에 서로 다른 글이 줄줄이 있으면, 2번째부터
            # 표제를 물려주면 **다 같은 제목**이 된다 — 실측: 한 표제 밑이 72조각으로
            # 쪼개져 전부 「settings.json Stop 훅」이 됐고, 그래서 사본처럼 보였다.
            # 실은 「주소 판정」·「컷 비율」·「레이아웃 결함」 다 다른 글이었다.
            # 뒤엣것은 비워서 제 첫 줄에서 제목을 뽑게 한다(gate.제목뽑기).
            if 몇째 == 0 and 이름:
                쓴제목[이름] = 쓴제목.get(이름, 0) + 1
                제목 = 이름 if 쓴제목[이름] == 1 else f"{이름} ({쓴제목[이름]})"
            else:
                제목 = ""
            나온.append(조각(제목=제목, 몸=곁, 출처=출처, 줄=더한줄))

    # ★ **표제가 하나도 없는 파일에 파일 이름을 붙이지 않는다.**
    # 조각이 여럿이면 「파일이름 (7)」이 되는데 그것으로는 아무것도 못 떠올린다 —
    # 실사용에서 미리보기 스무 개가 **스무 개 다 그 꼴**로 나왔다.
    # 비워 두면 뒤에서 **첫 문장**을 제목으로 삼는다(`gate.제목뽑기`).
    # 원문에서 뽑은 말이라 「파일이름 (7)」보다 언제나 낫다.
    # 조각이 하나뿐일 때만 파일 이름이 제목 노릇을 한다.
    if len(나온) == 1 and not 나온[0].제목:
        나온[0] = 조각(제목=밑동 or "무제", 몸=나온[0].몸,
                     출처=나온[0].출처, 줄=나온[0].줄)
    return 나온


# 밑줄로 긋는 표제. **`#` 만 표제로 보면 `===`·`---` 로 긋는 글이 통째로 한 덩이**가
# 되고, 그러면 제목이 파일 이름으로 떨어진다. 실사용 자리에서 이 꼴이 나왔다:
#
#     ================================================================
#     13-14. ★★ 재는 길이 둘 생겼다
#     ================================================================
#
# 마크다운 표준(setext)은 밑에만 긋는 것인데 위아래로 감싸는 꼴도 흔하다.
# 감싼 것은 **위 줄이 그냥 줄자로 읽혀 넘어가고 아래 줄이 표제를 만든다** —
# 따로 다룰 것이 없다.
_줄자 = re.compile(r"^\s*([=\-*_])\1{2,}\s*$")
# `--- 무엇 ---` 처럼 양옆을 두른 꼴.
_두른것 = re.compile(r"^\s*-{2,}\s*(.+?)\s*-{2,}\s*$")


def _표제(줄: str, 다음: str) -> str:
    """이 줄이 표제면 그 글, 아니면 빈 글."""
    m = re.match(r"^(#{1,4})\s+(.+)$", 줄)
    if m:
        return m.group(2).strip()
    글 = 줄.strip()
    if not 글 or _줄자.match(줄):
        return ""                      # 줄자 자체는 표제가 아니다
    if 두름 := _두른것.match(줄):
        return 두름.group(1).strip()
    # 밑줄이 그어져 있으면 표제다. **너무 긴 줄은 아니다** — 본문 한 문단 뒤에
    # 구분선이 오는 일이 흔한데, 그걸 표제로 삼으면 문단 통째가 제목이 된다.
    if _줄자.match(다음) and len(글) <= 60:
        return 글
    return ""


def _쪼개기(몸: str, 첫줄: int) -> list[tuple[str, int]]:
    """긴 도막을 빈 줄에서 나눈다. **문단 한복판은 안 자른다.**

    글자 수로만 자르면 「그래서 이것은」에서 끊긴 조각이 생기고, 그 조각은
    혼자 읽으면 아무 뜻이 없다. 빈 줄이 없으면 통째로 둔다 — 길어도 뜻은 남는다.
    """
    if len(몸) <= 긴조각:
        return [(몸, 첫줄)] if 몸 else []
    나온: list[tuple[str, int]] = []
    담을: list[str] = []
    줄수, 시작 = 0, 첫줄
    for 문단 in 몸.split("\n\n"):
        if 담을 and sum(len(x) for x in 담을) + len(문단) > 긴조각:
            나온.append(("\n\n".join(담을), 시작))
            시작 += 줄수
            담을, 줄수 = [], 0
        담을.append(문단)
        줄수 += 문단.count("\n") + 2
    if 담을:
        나온.append(("\n\n".join(담을), 시작))
    return 나온


def 버릴까(c: 조각) -> str:
    """싼 문지기. 읽지 않고도 아는 것만 본다. 버릴 이유를 돌려주고, 없으면 빈 글."""
    if len(c.몸) < 짧은조각:
        return "너무 짧다"
    if 기계글.match(Path(c.출처).name):
        return "사람이 안 쓴 글"
    # 기호가 절반 가까이면 코드·설정이다. 뜻 벡터가 이런 것에서는 아무 데나 붙는다.
    글자 = sum(1 for ch in c.몸 if ch.isalnum() or ch.isspace())
    if 글자 / max(1, len(c.몸)) < 0.55:
        return "글이 아니라 기호 덩어리"
    # 울타리 안이 몸의 대부분이면 코드 조각이다.
    코드 = sum(len(x) for x in re.findall(r"```.*?```", c.몸, re.S))
    if 코드 > len(c.몸) * 0.6:
        return "거의 코드"
    return ""


@dataclass
class 셈:
    본것: int = 0
    들인것: int = 0
    겹친것: int = 0
    버린것: dict[str, int] = field(default_factory=dict)

    def 버림(self, 이유: str) -> None:
        self.버린것[이유] = self.버린것.get(이유, 0) + 1

    def __str__(self) -> str:
        버린 = " · ".join(f"{k} {v}" for k, v in
                          sorted(self.버린것.items(), key=lambda x: -x[1]))
        # ★ **「들인 것」이라 적었더니 「저장된 수」로 읽혔다.** 이 수는 싼 문지기를
        #   지난 **후보**이고, 그 뒤 비싼 문지기가 또 거른다 — 시험 쪽이 「들인 것 5」와
        #   최종 저장 0 을 나란히 보고 헷갈렸다. **이름이 셈을 거짓말하게 두면 안 된다.**
        return (f"본 것 {self.본것} · 후보 {self.들인것} · "
                f"겹친 것 {self.겹친것} · 버린 것: {버린 or '없음'}")


def 훑기(뿌리: str | Path, 끝: tuple[str, ...] = (".md", ".txt")) -> list[Path]:
    """들일 만한 파일만 골라 온다. 남의 것은 여기서 걷어낸다."""
    뿌리 = Path(뿌리)
    if not 뿌리.is_dir():
        return []
    return sorted(p for p in 뿌리.rglob("*")
                  if p.is_file() and p.suffix.lower() in 끝
                  and not 남의것.search(str(p.relative_to(뿌리))))


def 읽기(p: Path) -> str:
    """어떤 인코딩으로 적혔든 읽는다. 못 읽으면 빈 글 — 한 파일 때문에 안 멈춘다."""
    for enc in ("utf-8-sig", "utf-8", "cp949"):
        try:
            return p.read_text(encoding=enc)
        except (UnicodeDecodeError, OSError):
            continue
    return ""


def 들일것(뿌리: str | Path, 이미: set[str] | None = None) -> tuple[list[조각], 셈]:
    """한 뿌리를 통째로 훑어 **들일 조각과 셈**을 돌려준다. 쓰지는 않는다.

    쓰는 일을 여기서 안 하는 이유: 먼저 무엇이 들어올지 사람이 봐야 한다.
    수천 개를 말없이 쌓고 나면 되돌릴 길이 없다.

    ★★ `이미` 는 **기록에 이미 든 글의 지문**이다. 안 주면 이번 판 안에서만 겹침을
    본다 — 그러면 **같은 폴더를 두 번 흡수할 때 통째로 다시 쌓인다.**
    실제로 오너 기록 3183장 중 **388장(12.2%)** 이 그렇게 생겼다.
    자료가 없어서가 아니라 **안 봐서** 생긴 것이다.
    """
    뿌리 = Path(뿌리)
    나온: list[조각] = []
    본지문: set[str] = set(이미 or ())
    s = 셈()
    for p in 훑기(뿌리):
        raw = 읽기(p)
        if not raw.strip():
            s.본것 += 1
            s.버림("빈 파일")
            continue
        출처 = str(p.relative_to(뿌리)).replace("\\", "/")
        조각들 = 조각내기(raw, 출처)
        if not 조각들:
            # ★ **조각이 하나도 안 나오는 파일도 본 것이다.** 안 세면
            # 「본 것 = 들인 것 + 겹친 것 + 버린 것」이 깨져서 「내 파일을 다 봤나」에
            # 틀린 답을 준다 — 파일 셋을 넣었는데 본 것이 2로 나왔다.
            s.본것 += 1
            s.버림("빈 파일")
            continue
        for c in 조각들:
            s.본것 += 1
            이유 = 버릴까(c)
            if 이유:
                s.버림(이유)
                continue
            if c.지문 in 본지문:
                s.겹친것 += 1
                continue
            본지문.add(c.지문)
            나온.append(c)
            s.들인것 += 1
    return 나온, s


def _self_check() -> None:
    # 표제를 따라 나눈다 — 사람이 나눠 놓은 자리가 뜻이 갈리는 자리다.
    글 = "머리말이 여기 있다\n\n## 첫 도막\n" + "가" * 60 + "\n\n## 둘째 도막\n" + "나" * 60
    조각들 = 조각내기(글, "본보기.md")
    assert [c.제목 for c in 조각들][-2:] == ["첫 도막", "둘째 도막"], [c.제목 for c in 조각들]
    assert 조각들[-1].줄 > 조각들[-2].줄, "줄 번호가 안 는다"

    # ★ **코드 울타리 안의 우물 정은 표제가 아니다.** 안 그러면 파이썬 파일 하나가
    # 주석 수만큼 조각난다 — 흡수에서 제일 많이 생길 쓰레기다.
    코드글 = "## 진짜 표제\n" + "설명" * 30 + "\n\n```python\n# 이건 주석이다\nx = 1\n```\n"
    assert [c.제목 for c in 조각내기(코드글, "ㄱ.md")] == ["진짜 표제"], \
        [c.제목 for c in 조각내기(코드글, "ㄱ.md")]

    # 표제가 없으면 파일 이름을 쓴다. 「무제」가 수백 개면 못 찾는다.
    assert 조각내기("표제 없는 글" + "다" * 60, "회의록.md")[0].제목 == "회의록"

    # ★ **제목이 겹치면 못 찾는다.** 같은 표제가 한 파일에 두 번 나오는 일이 흔하다.
    두번 = "## 남긴 것\n" + "가" * 60 + "\n\n## 남긴 것\n" + "나" * 60
    assert [c.제목 for c in 조각내기(두번, "ㄷ.md")] == ["남긴 것", "남긴 것 (2)"], \
        [c.제목 for c in 조각내기(두번, "ㄷ.md")]

    # ★★ **`#` 만 표제로 보면 `===`·`---` 로 긋는 글이 통째로 한 덩이가 된다.**
    # 그러면 제목이 파일 이름으로 떨어지고, 조각이 여럿이면 「파일이름 (7)」이 된다 —
    # 실사용에서 미리보기 스무 개가 **스무 개 다 그 꼴**로 나왔다.
    줄자 = "=" * 40
    감싼 = (줄자 + chr(10) + "13-14. 재는 길이 둘 생겼다" + chr(10) + 줄자 + chr(10) * 2
            + "앞머리 본문이다. 조각이 살 만큼 길게 적는다." * 3 + chr(10) * 2
            + "--- 13-14-1. 이음선 ---" + chr(10) * 2
            + "카드 여덟 장을 스위치 하나로 바꿨다." * 3)
    이름들 = [c.제목 for c in 조각내기(감싼, "VC-점검보고-20260901.md")]
    assert "13-14. 재는 길이 둘 생겼다" in 이름들, 이름들
    assert "13-14-1. 이음선" in 이름들, 이름들
    # 줄자 자체는 표제가 아니다. 그걸 표제로 삼으면 「=======」가 제목이 된다.
    assert not any(set(t) <= set("= ") for t in 이름들 if t), 이름들

    # 본문 뒤에 오는 구분선은 표제를 만들지 않는다 — 그러면 문단이 제목이 된다.
    긴줄 = "이건 아주 긴 본문 한 줄이라 표제로 보면 안 된다. " * 3
    assert 긴줄.strip() not in [c.제목 for c in 조각내기(긴줄 + chr(10) + 줄자, "ㄱ.md")]

    # ★ **표제가 하나도 없고 조각이 여럿이면 파일 이름을 안 붙인다.** 비워 두면
    # 뒤에서 첫 문장을 쓴다 — 「파일이름 (7)」보다 언제나 낫다.
    # ★★ **앞머리(front matter)는 글이 아니다.** 그냥 두면 「title: 무엇」이 표제로
    # 잡히고 몸은 `---` 한 줄만 남는다 — 실사용에서 그런 항목이 둘 들어왔다.
    앞 = ("---" + chr(10) + "title: OUR MEMORIES 운영·인수인계" + chr(10)
          + "갈래: 인수인계" + chr(10) + "---" + chr(10) * 2
          + "여기가 진짜 본문이다. 조각이 살 만큼 길게 적는다." * 3)
    ㅁ = 조각내기(앞, "OUR-MEMORIES-인수인계.md")
    assert len(ㅁ) == 1, [c.제목 for c in ㅁ]
    # `title:` 값을 그 문서의 이름으로 쓴다 — 사람이 적어 둔 이름이라 파일 이름보다 낫다.
    assert ㅁ[0].제목 == "OUR MEMORIES 운영·인수인계", ㅁ[0].제목
    assert "title:" not in ㅁ[0].몸 and "---" not in ㅁ[0].몸, ㅁ[0].몸[:60]
    # ★ **줄 번호는 원본 파일 기준이어야 한다.** 앞머리를 건너뛴 만큼 밀려야 한다 —
    # 항목이 지고 다니는 것이 이 값이라 어긋나면 원본으로 되돌아갈 길이 틀어진다.
    # (표제가 없으면 앞머리 바로 다음 줄을 가리킨다. 표제가 있으면 그 표제 줄이다 —
    #  진짜 볼트 파일로도 재 봤고 거기서는 `#` 표제가 있는 6번째 줄이 나왔다.)
    assert ㅁ[0].줄 == 5, ㅁ[0].줄

    # 앞머리가 안 닫혔으면 앞머리가 아니다. 손대지 않는다.
    안닫힘 = "---" + chr(10) + "title: 무엇" + chr(10) + "본문이 이어진다. " * 20
    assert any("title: 무엇" in c.몸 or c.제목 == "무엇" for c in 조각내기(안닫힘, "ㄱ.md"))

    # 긴 도막은 **빈 줄에서** 나뉜다. 문단을 여럿 둬야 조각이 여럿이 된다.
    민글 = (chr(10) * 2).join(["표제가 하나도 없는 글이다. " * 40] * 3)
    여럿 = 조각내기(민글, "VC-점검보고-20260829.md")
    assert len(여럿) > 1 and all(not c.제목 for c in 여럿), [c.제목 for c in 여럿]
    # 조각이 하나뿐이면 파일 이름이 제목 노릇을 한다(그때는 겹칠 일이 없다).
    assert 조각내기("짧은 글이다. " * 12, "회의록.md")[0].제목 == "회의록"

    # 긴 도막은 **빈 줄에서만** 나눈다. 문단 한복판에서 끊긴 조각은 뜻이 없다.
    긴글 = "\n\n".join("문단" * 200 for _ in range(4))
    도막들 = 조각내기(긴글, "긴.md")
    assert len(도막들) > 1, "긴 글이 안 쪼개진다"
    assert all("문단문단" in c.몸 for c in 도막들), "문단 한복판이 잘렸다"

    # 빈 줄이 없으면 통째로 둔다 — 길어도 뜻은 남는다. 자르면 그것마저 없어진다.
    한덩이 = "붙은글" * 900
    assert len(조각내기(한덩이, "ㄴ.md")) == 1, "빈 줄이 없는데 잘랐다"

    # 싼 문지기 — 읽지 않고도 아는 것만 본다.
    def 재보기(몸, 출처="ㄱ.md"):
        return 버릴까(조각(제목="ㄱ", 몸=몸, 출처=출처, 줄=1))

    assert 재보기("짧다") == "너무 짧다"
    assert 재보기("글" * 60, "LICENSE") == "사람이 안 쓴 글"
    assert 재보기("{[]}<>|&^%$#@!" * 20).startswith("글이 아니라")
    assert 재보기("설명 한 줄\n\n```\n" + "code();\n" * 40 + "```") == "거의 코드"
    # ★ **되는 글은 통과해야 한다.** 문지기만 재고 통과를 안 재면, 전부 버리는
    # 문지기도 검사를 통과한다.
    assert 재보기("어제 회의에서 정한 것은 다음 판부터 소리를 뒤로 미룬다는 것이다."
                  " 장비가 없어 잴 수가 없기 때문이다.") == "", "멀쩡한 글을 버린다"

    # 같은 글은 공백만 달라도 한 벌로 본다 — 같은 문서가 두 폴더에 있는 일이 흔하다.
    ㄱ = 조각(제목="ㄱ", 몸="같은  글이다\n\n두 줄로", 출처="a.md", 줄=1)
    ㄴ = 조각(제목="ㄴ", 몸="같은 글이다 두 줄로", 출처="b.md", 줄=9)
    assert ㄱ.지문 == ㄴ.지문, "공백만 다른데 다른 글로 본다"

    # 남의 것은 훑지도 않는다. 안 걸러내면 이것들이 항목의 대부분이 된다.
    import tempfile
    with tempfile.TemporaryDirectory() as d:
        뿌리 = Path(d)
        (뿌리 / "내글.md").write_text("## 내 것\n" + "글" * 60, encoding="utf-8")
        (뿌리 / "node_modules").mkdir()
        (뿌리 / "node_modules" / "남의글.md").write_text("남의 것" * 40, encoding="utf-8")
        assert [p.name for p in 훑기(뿌리)] == ["내글.md"], [p.name for p in 훑기(뿌리)]
        골라낸, s = 들일것(뿌리)
        assert s.들인것 == 1 and 골라낸[0].출처 == "내글.md", str(s)
        # 원본은 그 자리에 그대로 있다. 옮기면 두 벌이 되고 어느 쪽이 참인지 모른다.
        assert (뿌리 / "내글.md").exists(), "원본을 건드렸다"

    print("ingest self-check 통과")


