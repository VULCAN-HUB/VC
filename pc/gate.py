    # 떼고 남는 것이 너무 짧으면 안 뗀다 — 「3) 셋」이 「셋」이 되면 더 못 찾는다.
    assert _다듬기("3) 셋") == "3) 셋"

    # ★ **자를 때 낱말 한복판을 안 자른다.** 실사용에서 「…틀렸다. 그게 더」처럼
    # 말이 끊겨 나왔다.
    긴것 = _다듬기("3번 결과를 어떻게 볼지 → 네 진단 하나가 틀렸다. 그게 더 중요했다고 본다")
    assert 긴것.endswith("…") and len(긴것) <= 41, 긴것
    assert not 긴것.rstrip("…").endswith(" "), 긴것
    # 짧은 것은 안 자르고 꼬리표도 안 붙인다.
    assert _다듬기("짧은 제목") == "짧은 제목"

    # ★★ **괄호가 열린 채 끝나면 그 앞에서 끊는다.** 실사용에서 나온 그대로다 —
    # 「(2026-07-11(2), 커밋 245bfbf」 까지 남기느니 「후속 4건」이 낫다.
    괄 = _다듬기("후속 4건 (2026-07-11(2), 커밋 245bfbf·6d034dc·9a1f2e3 를 되돌렸다)")
    assert 괄 == "후속 4건…", 괄
    괄2 = _다듬기("Second Brain — Vault 규칙 (Claude 저장·참조 계약과 승격 게이트)")
    assert 괄2 == "Second Brain — Vault 규칙…", 괄2
    # 괄호가 제대로 닫혀 있으면 건드리지 않는다.
    assert _열린괄호("가 (나) 다") is None
    assert _열린괄호("가 (나 [다]") == 2
    # 여는 괄호가 너무 앞이면 거기서 끊지 않는다 — 두 글자만 남는 것보다 낫다.
    짧괄 = _다듬기("가 (아주 긴 괄호 안 설명이 여기서부터 계속 이어지고 또 이어진다")
    assert len(짧괄) > 6, 짧괄

    # ★ 첫 문장으로 떨어질 때 **줄자와 표 머리는 건너뛴다.** 실제로 「========」가
    # 제목으로 나왔다.
    줄자몸 = "=" * 40 + chr(10) + "여기가 진짜 첫 문장이다. 뒤는 더 있다."
    assert 제목뽑기(조각(제목="", 몸=줄자몸, 출처="", 줄=1)) == "여기가 진짜 첫 문장이다."
    assert 제목뽑기(조각(제목="", 몸="=" * 40, 출처="", 줄=1)) == "무제"

    # ★★ **날짜가 적혀 있다고 일정이 아니다.** 글에는 날짜가 그냥 널려 있다 —
    # 실사용에서 미리보기 스무 개 중 **열넷**이 「일정」으로 찍혔고 그중엔
    # 날짜도 기한도 없는 표가 섞여 있었다.
    표 = 조각(제목="", 몸="물음 | 1등 | 맞나 | 2등" + chr(10) + "2026-09-01 에 잰 것이다.",
              출처="a.md", 줄=1)
    assert 갈래(표, 표.몸) == "일", 갈래(표, 표.몸)
    # 언제까지 무엇을 한다는 말이 있어야 일정이다.
    for 진짜 in ("3월 12일까지 내야 한다", "마감이 내일이다", "다음 주에 보내기로 했다"):
        ㄹ = 조각(제목="", 몸=진짜, 출처="a.md", 줄=1)
        assert 갈래(ㄹ, 진짜) == "일정", (진짜, 갈래(ㄹ, 진짜))

    # ★ **버린다면 짓지 않는다.** 대부분이 여기서 떨어지므로 이게 곧 값이다.
    # 두 번째 답을 안 줬는데도 안 터진다면 2단계를 안 부른 것이다.
    p = 물어보기(ㄱ, 짜기("버린다"))
    assert not p.남긴다 and not p.못알아들음, p

    # 말끝이 붙어도 알아듣는다. 작은 모델은 「남긴다.」 「**버린다**」처럼 낸다.
    assert 가름("ㄱ", 짜기("버린다."))[0] is False
    assert 가름("ㄱ", 짜기("**남긴다**"))[0] is True

    # ★ **둘 다 아닌 답은 「버린다」가 아니라 「못 알아들었다」다.**
    # 뭉뚱그리면 모델이 헛소리를 할수록 기록이 조용히 줄어든다.
    for 엉망 in ("", "글쎄요", "yes", "1"):
        남길까, 몰랐나 = 가름("ㄱ", 짜기(엉망))
        assert 남길까 and 몰랐나, 엉망

    # ★ 못 지으면 **조각을 그대로 쓴다.** 못 지었다고 안 남기면 값을 지키려다
    # 물건을 잃는다. 마지막 것은 모델이 안내문 괄호를 그대로 베껴 온 꼴이다.
    for 엉망 in ("", "무슨 말인지 모르겠습니다", "제목:", "제목: (15자 안쪽. 떠올릴 말)"):
        제목, 몸, 못지음 = 짓기(ㄱ, 짜기(엉망))
        assert (제목, 몸) == (ㄱ.제목, ㄱ.몸) and 못지음, 엉망

    # 간추림만 없으면 제목은 살린다 — 제목이 곧 찾는 길이다.
    제목, 몸, 못지음 = 짓기(ㄱ, 짜기("제목: 소리 보류"))
    assert 제목 == "소리 보류" and 몸 == ㄱ.몸 and 못지음

    # 모델이 죽어도 흡수는 안 멈춘다 — 죽은 자리에서 서면 7천 개를 못 넘긴다.
    def 죽는다(_):
        raise RuntimeError("모델 없음")
    p = 물어보기(ㄱ, 죽는다)
    assert p.남긴다 and p.못알아들음 and p.몸 == ㄱ.몸, p

    # 갈래는 모델에 안 묻고 글자로 짚는다. 못 짚으면 「일」.
    빈 = 조각(제목="", 몸="", 출처="", 줄=1)
    assert 갈래(빈, "3월 12일까지 내야 한다") == "일정"
    assert 갈래(빈, "절대 이렇게 하지 마") == "규칙"
    assert 갈래(빈, "그냥 고쳤다") == "일"

    # 무더기로 태우면 셈이 맞는다.
    답들 = iter(["남긴다", "버린다", "몰라요"])
    남길, s, 막힌것 = 거르기([ㄱ, ㄱ, ㄱ], lambda _: next(답들))
    assert (s.본것, s.남긴것, s.버린것, s.못알아들은것) == (3, 2, 1, 1), str(s)
    # 안 지으므로 셋 다 원문 그대로. 「몰라요」도 막지 않고 남는다.
    assert all(판.몸 == ㄱ.몸 for _, 판 in 남길), [판.몸 for _, 판 in 남길]
    # ★ 못 알아들은 몫이 셈에 보여야 한다. 안 보이면 「문지기가 일을 하는 것」과
    # 「그냥 다 통과시키는 것」을 구별할 길이 없다.
    assert "못 알아들은 것" in str(s), str(s)

    # ★★ **통째로 죽은 문지기는 「다 통과」로 보인다.** 구운 exe 에서 1058개가
    # 1초 만에 전부 통과했는데 셈만 보면 멀쩡해 보였다. 그래서 둘을 남긴다 —
    # 왜 죽었는지(`탈`)와, 이게 문지기 노릇을 한 것이 맞는지(`죽었나`).
    def 늘죽는다(_):
        raise RuntimeError("llama.dll 을 못 열었다")
    _, 죽은셈, _막1 = 거르기([ㄱ, ㄱ, ㄱ], 늘죽는다)
    assert 죽은셈.죽었나, 죽은셈
    assert "llama.dll" in 죽은셈.탈, 죽은셈.탈
    assert "못 알아들은 것 3 (100%)" in str(죽은셈), str(죽은셈)

    # 멀쩡히 돌면 죽었다고 안 한다 — 다 죽었다고 하면 그것도 재는 게 아니다.
    답들2 = iter(["남긴다", "버린다", "남긴다"])
    _, 산셈, _막2 = 거르기([ㄱ, ㄱ, ㄱ], lambda _: next(답들2))
    assert not 산셈.죽었나 and not 산셈.탈, 산셈

    # ★★ **같은 제목을 두 번 보내면 조용히 덮어쓴다.** 항목 쓰기는 같은 제목을
    # 「고치는 것」으로 보므로(그게 옳다), 갈라 주는 일은 이쪽 몫이다.
    있던 = {"Context"}
    ㄴ = 겹치지않게("Context", "pc-sharing-smb", 있던)
    assert ㄴ == "Context (pc-sharing-smb)", ㄴ

    # ★ **겹치지 않아도 너무 짧으면 붙인다.** 「참고」 「예외」 「후속」 으로는
    # 몇 달 뒤에 못 찾는다. 안 겹친 것은 **아직** 안 겹친 것일 뿐이다.
    assert 겹치지않게("참고", "workspace-storage-rule", set()) \
        == "참고 (workspace-storage-rule)"
    assert 겹치지않게("예외", "", set()) == "예외"      # 어디서 왔는지 모르면 그냥 둔다
    # 넉넉히 긴 제목은 안 건드린다 — 멀쩡한 제목에 괄호가 붙으면 그게 더 나쁘다.
    assert 겹치지않게("빈 자리에 손이 얹혀 있으면", "ㄱ", set()) == "빈 자리에 손이 얹혀 있으면"
    있던.add(ㄴ)
    # 같은 문서에서 또 겹치면 그때 번호가 붙는다.
    ㄷ = 겹치지않게("Context", "pc-sharing-smb", 있던)
    assert ㄷ == "Context (pc-sharing-smb 3)", ㄷ
    # 안 겹치면 손대지 않는다 — 멀쩡한 제목에 괄호가 붙으면 그게 더 나쁘다.
    assert 겹치지않게("아주 딴 이야기", "아무거나", 있던) == "아주 딴 이야기"
    # 어디서 왔는지 모르면 번호라도 붙인다. **덮어쓰는 것보다는 낫다.**
    assert 겹치지않게("Context", "", {"Context"}) == "Context (2)"

    # ★★ **규칙 문서는 문지기가 버린다고 해도 남긴다.** 규칙 알맹이가 통째로
    # 버려지는 것을 시험하는 쪽이 짚었다 — 표제만 남고 「무엇을 하기로 했나」가 없어졌다.
    규칙쪽 = 조각(제목="", 몸="아무 말이나 적혀 있다.", 출처="CLAUDE.md", 줄=1)
    p = 물어보기(규칙쪽, 짜기("버린다"))
    assert p.남긴다 and "규칙 문서라" in p.왜, p
    # 규칙 문서가 아니면 그대로 버린다 — 다 남기면 문지기가 아니다.
    보통 = 조각(제목="", 몸="아무 말이나 적혀 있다.", 출처="회의록.md", 줄=1)
    assert not 물어보기(보통, 짜기("버린다")).남긴다
    # 이름으로 가른다. 사람이 붙인 이름이라 짐작이 아니다.
    for 참 in ("CLAUDE.md", "AGENTS.md", "wiki/저장-규칙.md", "guidelines/naming-rules.md",
               "개인정보 보호 원칙.txt", "d/e/policy.md"):
        assert 규칙문서인가(참), 참
    for 거짓 in ("회의록.md", "log.md", "index.md", "VC-점검보고-20260901.txt",
                 "raw/2026-09-02-session.md"):
        assert not 규칙문서인가(거짓), 거짓

    # ★★ **사람은 규칙을 규칙 문서에만 적지 않는다.** 일하다가 「이건 이렇게 하기로」를
    # 그날 기록에 적고, **그렇게 적힌 것이 나중에 더 자주 찾는 것**이다(왜 그렇게
    # 정했는지가 같이 있다). 시험하는 쪽이 세션 기록 안의 규칙 셋이 여전히 막히는 것을
    # 짚었다. **줄 앞에 사람이 붙인 딱지만** 본다 — 낱말로 넓히면 못 쓴다.
    딱지쪽 = 조각(제목="", 몸="이것저것 했다." + chr(10) + "**결정**: 앞으로는 이렇게 한다.",
                  출처="raw/2026-09-02-session.md", 줄=1)
    구할까, 까닭 = 구제할까(딱지쪽)
    assert 구할까 and "적어 둬서" in 까닭, (구할까, 까닭)
    p = 물어보기(딱지쪽, 짜기("버린다"))
    assert p.남긴다 and "적어 둬서" in p.왜, p
    for 참 in ("규칙: 늘 이렇게", "  - 교훈: 이러면 안 된다", "**원칙**: 하나만", "주의：여기 조심"):
        assert 구제할까(조각(제목="", 몸=참, 출처="ㄱ.md", 줄=1))[0], 참
    # **낱말이 그냥 들어 있는 것은 아니다.** 넓히면 막은 것의 3할이 되살아난다.
    for 거짓 in ("규칙을 확인했다", "그 결정이 좋았다", "교훈이라 할 만하다",
                 "이 원칙은 지켜졌다"):
        assert not 구제할까(조각(제목="", 몸=거짓, 출처="ㄱ.md", 줄=1))[0], 거짓

    # ★ **붙이는 이름이 길면 제목이 못 읽게 된다.** 날짜와 꼬리말을 뗀다.
    assert 겹치지않게("기술스택", "2026-07-01-ourmemories-session", set()) \
        == "기술스택 (ourmemories)", 겹치지않게("기술스택", "2026-07-01-ourmemories-session", set())
    assert 겹치지않게("큰 그림", "2026-07-11-ourmemories-public-redesign", set()) \
        == "큰 그림 (ourmemories-public-redesign)"

    # ★★ **잃은 수 셈.** 한 번 틀려서 **정상인데 「-529개가 겹쳐 덮였다」**가 찍혔다.
    # 「쓴 것」을 기록 **전체** 항목 수와 견줬기 때문이다 — 빈 자리에 처음 쓸 때만
    # 맞는 셈이었다. 거짓 경보는 없는 문제를 쫓게 한다.
    assert 잃은수(188, 529, 717) == 0, 잃은수(188, 529, 717)   # 실제로 겪은 자리
    assert 잃은수(31, 0, 29) == 2                              # 31 썼는데 29만 늘었다
    assert 잃은수(31, 0, 31) == 0
    assert 잃은수(0, 529, 529) == 0
    # **는 것이 쓴 것보다 많아도 경보가 아니다** — 밖에서 파일이 늘 수 있다.
    assert 잃은수(10, 100, 130) == 0

    # ★ **물음이 짧아야 한다.** 길어지면 모델이 판단 대신 그걸 베낀다 —
    # 승격 물음 아홉 개를 늘어놓았을 때 30개 중 30개가 통과했다.
    assert len(가름틀) < 400, f"가름 물음이 길어졌다: {len(가름틀)}자"
    # 일상 쪽이 살아 있다. 일 쪽만 남기면 「치과 3시」가 떨어진다.
    assert "약속·일정" in 가름틀 and "못 떠올릴 사실" in 가름틀

    print("gate self-check 통과")


