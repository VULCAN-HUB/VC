    # ★ **번호가 붙은 멀쩡한 표제를 버리면 안 된다.** 처음엔 「숫자가 있는데 글자가
    # 몇 자 없으면 이름표」로 잡았는데 너무 넓었다 — 「13-14-2. 찾기 등수」는
    # 글자가 넷뿐이지만 훌륭한 제목이다. 이름표 꼴은 **괄호로 시작한다.**
