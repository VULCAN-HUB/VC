def _self_check() -> None:
    from pathlib import Path
    # 갈래는 층을 하나씩 정한다
    assert 층(원본갈래) == RAW
    assert all(층(k) == WIKI for k in 갈래들 if k != 원본갈래), "raw 갈래가 둘 이상이다"
    assert 아는갈래(기본갈래) and not 아는갈래("없는갈래ZZZ")
    # VC 가 쓰던 옛 갈래는 나무라지 않는다. 볼트 갈래는 **옮겨야 하므로** 걸려야 한다.
    assert 아는갈래("note") and 아는갈래("agent"), "VC 가 쓰던 갈래를 모른다고 한다"
    assert not 아는갈래("dev-task"), "옮겨야 할 볼트 갈래를 아는 척한다"
    assert 가운데항목 not in 갈래들
    assert 자리("결정", "2026/09") == "wiki/2026/09", 자리("결정", "2026/09")
    assert 자리(원본갈래, "2026/09") == "raw/2026/09", 자리(원본갈래, "2026/09")

    # ★ 주소 하나만 친 것은 **찾는 말이 아니라 모을 것**이다(오너는 크롬을 주로 쓴다).
    assert 주소인가("https://quasarzone.com/bbs/qn_hardware/views/2065297")
    assert 주소인가("  http://example.com/a?b=1  ")
    assert not 주소인가("고기 먹음") and not 주소인가("http://a b")
    assert not 주소인가(""), "빈 글을 주소로 본다"
    # 제목은 **주소가 아니라 사람 말**이어야 한다 — 주소를 제목에 쓰면 파일 이름이 깨진다
    assert 원본제목("https://www.quasarzone.com/bbs/x") == "링크 · quasarzone.com"
    assert 원본제목("https://example.com") == "링크 · example.com"
    assert "/" not in 원본제목("https://a.b/c/d") and ":" not in 원본제목("https://a.b/c/d")

    글 = 스키마글()
    # ★★ **글은 표에서 짓는다.** 두 군데 적으면 갈라진다 — 갈래를 더하고 글을 안 고치면
    #   사람과 AI 가 다른 목록을 보게 된다. 그래서 **모든 갈래·앞머리·연산이 글에 있는지** 잰다.
    for 이름 in 갈래들:
        assert f"`{이름}`" in 글, f"갈래 「{이름}」 이 규칙 글에 없다"
    for 이름, 값들 in 앞머리규약.items():
        assert f"`{이름}`" in 글, f"앞머리 「{이름}」 이 규칙 글에 없다"
        for v in 값들:
            assert v in 글, f"앞머리 값 「{v}」 가 규칙 글에 없다"
    for 이름 in 연산들:
        assert f"**{이름}**" in 글, f"일 「{이름}」 이 규칙 글에 없다"
    assert "archive/` 를 두지 않는다" in 글, "archive 를 안 둔다는 말이 빠졌다"
    assert RAW + "/" in 글 and WIKI + "/" in 글
    # 규칙 글은 **사람이 읽는 것이기도 하다** — 표만 있고 설명이 없으면 안 된다
    assert 글.count(chr(10) + "## ") >= 6, "칸이 모자라다"

    # ★★ **옛 갈래로 새 글을 쓰는 자리가 남았나.** 자리를 하나씩 세다가 두 번 놓쳤다
    #   (2026-09-21: 처음에 넷을 고치고 「이제 안 샌다」고 했는데 씨앗·제품 정리가 더
    #   있었다). 이제 **소스를 통째로 훑어** 잡는다 — 새 자리가 생겨도 걸린다.
    #   검사 코드는 옛 창고를 흉내 내야 하므로 뺀다.
    import re as _re

    # ★ **아직 못 옮긴 둘.** 지울 때마다 이유를 다시 읽게 여기 적어 둔다.
    #   새 자리가 생기면 이 표에 없으니 검사가 잡는다 — 가드의 힘은 그대로다.
    아직 = {
        # 오너가 「나에 대해는 아직 신경쓰지 마라」 했다(2026-09-21). 갈래를 옮기면
        # 설정을 저장할 때 그 글이 바뀐다 — 오너 글이라 묻고 한다.
        ("settings.py", "preference"),
    }
    옛것들 = []
    여기 = Path(__file__).resolve().parent
    for 파일 in sorted(여기.glob("*.py")):
        try:
            줄들 = 파일.read_text(encoding="utf-8").splitlines()
        except OSError:
            continue
        검사안 = False
        for 번, 줄 in enumerate(줄들, 1):
            if _re.match(r"def _self_check|def _check|if __name__", 줄):
                검사안 = True
            if 검사안 or 파일.name.endswith("_check.py"):
                continue
            m = _re.search(r'kind\s*=\s*"([^"]+)"', 줄)
            if m and m.group(1) in 옛갈래 and (파일.name, m.group(1)) not in 아직:
                옛것들.append(f"{파일.name}:{번}  {줄.strip()[:60]}")
    assert not 옛것들, "옛 갈래로 새 글을 쓰는 자리가 남았다:" + chr(10) + chr(10).join(옛것들)

    print("wiki self-check 통과")


if __name__ == "__main__":
    import sys

    if "--check" in sys.argv:
        _self_check()
